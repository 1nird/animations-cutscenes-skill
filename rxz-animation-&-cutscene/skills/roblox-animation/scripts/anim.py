"""Lint a pose spec and build it into a real KeyframeSequence.

    py scripts/anim.py lint examples/punch.json
    py scripts/anim.py build examples/punch.json --out out/

A spec is per-joint rotations in degrees. build writes three files: a .rbxmx
for the Animation Editor, a .luau builder for KeyframeSequenceProvider
(no upload), and a report.json the gate reads.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import animlib as A  # noqa: E402


def slug(text):
    return re.sub(r"[^A-Za-z0-9_-]+", "", text) or "Anim"


def fmt(value):
    text = f"{value:.6f}".rstrip("0").rstrip(".")
    return "0" if text in ("", "-0") else text


def pose_value(value):
    if isinstance(value, dict):
        return (float(value.get("x", 0.0)), float(value.get("y", 0.0)), float(value.get("z", 0.0)))
    return tuple(float(v) for v in value)


def cframe_xml(rot, pos=(0.0, 0.0, 0.0)):
    return (
        "<CoordinateFrame name=\"CFrame\">"
        f"<X>{fmt(pos[0])}</X><Y>{fmt(pos[1])}</Y><Z>{fmt(pos[2])}</Z>"
        f"<R00>{fmt(rot[0][0])}</R00><R01>{fmt(rot[0][1])}</R01><R02>{fmt(rot[0][2])}</R02>"
        f"<R10>{fmt(rot[1][0])}</R10><R11>{fmt(rot[1][1])}</R11><R12>{fmt(rot[1][2])}</R12>"
        f"<R20>{fmt(rot[2][0])}</R20><R21>{fmt(rot[2][1])}</R21><R22>{fmt(rot[2][2])}</R22>"
        "</CoordinateFrame>"
    )


def build_rbxmx(spec, name, rig):
    priority = A.PRIORITIES[spec["priority"]]
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<roblox xmlns:xmime="http://www.w3.org/2005/05/xmlmime" '
        'xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
        'xsi:noNamespaceSchemaLocation="http://www.roblox.com/roblox.xsd" version="4">',
        "  <External>null</External>",
        "  <External>nil</External>",
    ]
    ref = 1
    lines += [
        '  <Item class="KeyframeSequence" referent="RBX0">',
        "    <Properties>",
        f'      <string name="Name">{name}</string>',
        f'      <bool name="Loop">{"true" if spec["loop"] else "false"}</bool>',
        f'      <token name="Priority">{priority}</token>',
        "    </Properties>",
    ]
    for key in spec["keys"]:
        style, direction = A.EASE_MAP[key["ease"]]
        lines += [
            f'    <Item class="Keyframe" referent="RBX{ref}">',
            "      <Properties>",
            f'        <float name="Time">{fmt(key["t"])}</float>',
            "      </Properties>",
        ]
        ref += 1
        # Every joint, every key. A partial pose tree is the import trap.
        for joint in rig:
            rot = A.euler_matrix(*pose_value(key["pose"].get(joint, (0.0, 0.0, 0.0))))
            pos = key.get("root", (0.0, 0.0, 0.0)) if joint == "HumanoidRootPart" else (0.0, 0.0, 0.0)
            lines += [
                f'      <Item class="Pose" referent="RBX{ref}">',
                "        <Properties>",
                f'          <string name="Name">{joint}</string>',
                f"          {cframe_xml(rot, pos)}",
                f'          <token name="EasingStyle">{A.POSE_EASING[style]}</token>',
                f'          <token name="EasingDirection">{A.POSE_DIRECTION[direction]}</token>',
                '          <float name="Weight">1</float>',
                "        </Properties>",
                "      </Item>",
            ]
            ref += 1
        lines.append("    </Item>")
    lines += ["  </Item>", "</roblox>", ""]
    return "\n".join(lines)


def build_luau(spec, name, rig):
    lines = [
        f"-- {name} | {spec['duration']:.2f}s | {len(spec['keys'])} keys | {spec['priority']}",
        "-- Generated by rxz animation. Builds the KeyframeSequence in memory;",
        "-- no upload needed. Register it and assign the BARE id:",
        '--   local id = game:GetService("KeyframeSequenceProvider"):RegisterKeyframeSequence(sequence)',
        "--   anim.AnimationId = id   -- do not prefix hash:// or rbxasset://",
        "",
        "local keys = {",
    ]
    for key in spec["keys"]:
        style, direction = A.EASE_MAP[key["ease"]]
        lines.append(f'\t{{ t = {fmt(key["t"])}, style = Enum.PoseEasingStyle.{style}, '
                     f'dir = Enum.PoseEasingDirection.{direction}, poses = {{')
        for joint in rig:
            value = pose_value(key["pose"].get(joint, (0.0, 0.0, 0.0)))
            rot = A.euler_matrix(*value)
            pos = key.get("root", (0.0, 0.0, 0.0)) if joint == "HumanoidRootPart" else (0.0, 0.0, 0.0)
            base = ("CFrame.new(%s, %s, %s)" % (fmt(pos[0]), fmt(pos[1]), fmt(pos[2]))
                    if any(abs(v) > 1e-9 for v in pos) else "CFrame.new()")
            if rot == A.IDENT:
                cf = base
            else:
                cf = (base + " * CFrame.Angles(math.rad(%s), math.rad(%s), math.rad(%s))"
                      % (fmt(value[0]), fmt(value[1]), fmt(value[2])))
            lines.append(f'\t\t{{ "{joint}", {cf} }},')
        lines.append("\t} },")
    lines += [
        "}",
        "",
        "local function build()",
        '\tlocal sequence = Instance.new("KeyframeSequence")',
        f'\tsequence.Name = "{name}"',
        f'\tsequence.Loop = {"true" if spec["loop"] else "false"}',
        f'\tsequence.Priority = Enum.AnimationPriority.{spec["priority"]}',
        "\tfor _, key in ipairs(keys) do",
        '\t\tlocal frame = Instance.new("Keyframe")',
        "\t\tframe.Time = key.t",
        "\t\tfor _, entry in ipairs(key.poses) do",
        '\t\t\tlocal pose = Instance.new("Pose")',
        "\t\t\tpose.Name = entry[1]",
        "\t\t\tpose.CFrame = entry[2]",
        "\t\t\tpose.EasingStyle = key.style",
        "\t\t\tpose.EasingDirection = key.dir",
        "\t\t\tpose.Weight = 1",
        "\t\t\tpose.Parent = frame",
        "\t\tend",
        "\t\tframe.Parent = sequence",
        "\tend",
        "\treturn sequence",
        "end",
        "",
        "local sequence = build()",
        "return sequence",
        "",
    ]
    return "\n".join(lines)


def cmd_lint(args):
    spec = A.normalize(A.load_json(args.spec))
    rig_name, rig = A.load_rig(args.rig, spec.get("rig", "R15"))
    errors, warnings, stats = A.validate(spec, rig_name=rig_name, rig=rig)
    if args.json:
        print(json.dumps(A.report(spec, errors, warnings, stats), indent=2))
    else:
        print(f"{spec['name']}  {stats['duration']:.2f}s  {stats['frames']} frames  "
              f"{stats['keys']} keys  {stats['joints_used']} joints")
        print(f"priority {spec['priority']}  loop {spec['loop']}  "
              f"seam {stats['loop_seam_deg']:.1f} deg  "
              f"fastest {stats['fastest_joint'] or '-'} {stats['max_speed_dps']:.0f} deg/s")
        for w in warnings:
            print(f"WARN  {w}")
        for e in errors:
            print(f"FAIL  {e}")
        print("OK" if not errors else f"{len(errors)} error(s)")
    return 1 if errors else 0


def cmd_build(args):
    spec = A.normalize(A.load_json(args.spec))
    rig_name, rig = A.load_rig(args.rig, spec.get("rig", "R15"))
    errors, warnings, stats = A.validate(spec, rig_name=rig_name, rig=rig)
    if errors:
        for e in errors:
            print(f"FAIL  {e}", file=sys.stderr)
        return 1
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    name = args.name or slug(spec["name"])
    rbxmx = out / f"{name}.rbxmx"
    luau = out / f"{name}.luau"
    rbxmx.write_text(build_rbxmx(spec, name, rig), encoding="utf-8")
    luau.write_text(build_luau(spec, name, rig), encoding="utf-8")
    data = A.report(spec, errors, warnings, stats)
    data["files"] = {"rbxmx": str(rbxmx), "luau": str(luau)}
    (out / "anim.report.json").write_text(json.dumps(data, indent=2), encoding="utf-8")
    print(f"{name}: {rbxmx.name} {rbxmx.stat().st_size} B, {luau.name} {luau.stat().st_size} B"
          f" | root travel {stats.get('root_travel', 0):.2f} studs")
    for w in warnings:
        print(f"WARN  {w}")
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description="Lint and build Roblox animation specs.")
    sub = parser.add_subparsers(dest="cmd", required=True)
    lint = sub.add_parser("lint", help="check a spec without writing anything")
    lint.add_argument("spec")
    lint.add_argument("--rig", help="rig.json to author against instead of the built-in R15")
    lint.add_argument("--json", action="store_true")
    lint.set_defaults(func=cmd_lint)
    build = sub.add_parser("build", help="write .rbxmx, .luau and a report")
    build.add_argument("spec")
    build.add_argument("--out", default="out")
    build.add_argument("--name")
    build.add_argument("--rig", help="rig.json to author against instead of the built-in R15")
    build.set_defaults(func=cmd_build)
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
